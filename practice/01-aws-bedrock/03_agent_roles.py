import os
from dotenv import load_dotenv

from strands.agent import Agent
from strands.models.bedrock import BedrockModel

# Load environment variables from the .env file
load_dotenv()

# Replace 'model_id' with the ID of the model you want to use
model_id = os.getenv('AWS_BEDROCK_MODEL_ID')

# Initialize the Bedrock model with the specified model ID
model = BedrockModel(model_id=model_id)

# ==============================================================================
# CONVERSATION ROLES EXPLAINED (WITHOUT HISTORY)
#
# In modern chat models (e.g., AWS Bedrock Converse API), every interaction
# involves 3 fundamental roles:
#
# 1. "system"    -> Rules, behavior, and persona for the AI model.
#                   In Strands, defined via `system_prompt`.
#
# 2. "user"      -> The prompt or question sent by the human user.
#                   In Strands, passed as the input to `agent(user_message)`.
#
# 3. "assistant" -> The output or answer generated by the AI model.
#                   In Strands, returned by the agent invocation.
# ==============================================================================

# Role 1: SYSTEM
# Sets the model's persona, boundaries, and tone
system_prompt = (
    "You are an expert cloud architect. "
    "Provide clear, concise, and professional answers in 2-3 sentences."
)

# Initialize the agent with the "system" role
# Note: By default, Strands uses PrintingCallbackHandler which automatically streams
# the model output to stdout. Setting callback_handler=None disables automatic printing
# so you can control how and when the response is displayed.
agent = Agent(
    model=model,
    system_prompt=system_prompt,
    callback_handler=None
)

# Role 2: USER
# The input message coming from the user
user_prompt = "What is the primary benefit of using Amazon S3?"
print(f"\n[USER]: {user_prompt}")

# Role 3: ASSISTANT
# The response generated by the model
assistant_response = agent(user_prompt)

print(f"\n[ASSISTANT]: {assistant_response}")


