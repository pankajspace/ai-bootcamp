"""
report.py — the review file: Markdown for humans, JSON for systems.

PROC-2.1 says what a review file must contain; this module produces exactly that: identity, every
requirement with verdict + source URL + date, open questions, and the approval block. Nothing here is
generated by a model. (Deep Search Module 6: "A clean structured result".)
"""

from __future__ import annotations

from .schemas import TIER_NAMES, AssessmentReport

VERDICT_MARK = {"PASS": "✅ PASS", "FAIL": "❌ FAIL", "UNKNOWN": "❔ UNKNOWN", "NEEDS_REVIEW": "⚠️ NEEDS REVIEW", "NOT_APPLICABLE": "— n/a"}
OVERALL_TEXT = {
    "BLOCKED": "BLOCKED for this data tier",
    "CONDITIONAL": "CONDITIONAL — open items before a human decision",
    "READY_FOR_APPROVAL": "READY FOR HUMAN APPROVAL",
}


def to_markdown(rep: AssessmentReport) -> str:
    rq, pf = rep.request, rep.profile
    L: list[str] = []
    L.append(f"# Vendor risk assessment — {rq.vendor}")
    L.append("")
    L.append(f"**Question:** {rq.question}  ")
    L.append(f"**Data tier:** {rq.tier} ({TIER_NAMES.get(rq.tier, '')}) · **Users:** {rq.users} · **Requested by:** {rq.requested_by}  ")
    L.append(f"**Evidence as of:** {pf.as_of} · **Run:** `{rep.run_id}` · **LLM calls:** {rep.llm_calls} · **Est. cost:** ${rep.cost_usd:.4f} · **Time:** {rep.duration_s:.1f}s")
    L.append("")
    L.append(f"## Outcome: {OVERALL_TEXT[rep.overall]}")
    L.append("")
    L.append(rep.overall_reason)
    L.append("")
    L.append(f"> This is an input to the review, not an approval. Approvers for {rq.tier}: {', '.join(rep.approval.approver_roles) or 'see AI-5.1'}. "
             f"Approval status: **{rep.approval.status}**" + (f" by {rep.approval.decided_by} on {rep.approval.decided_on}" if rep.approval.decided_by else "") + ".")
    L.append("")

    L.append("## 1. Vendor identity")
    ent = pf.get("legal_entity")
    L.append(f"- Vendor: **{pf.vendor}** · official domain: `{pf.official_domain or 'unknown'}`")
    L.append(f"- Legal entity: {ent.display if ent else 'not established from public sources'}")
    L.append(f"- Pages read: {pf.pages_read} · rejected as a different company: {len(pf.rejected)} · quarantined for prompt injection: {len(pf.quarantined)}")
    L.append("")

    L.append("## 2. Requirements")
    L.append("")
    L.append("| Requirement | Clause | Verdict | Severity | Reason | Evidence | As of |")
    L.append("|---|---|---|---|---|---|---|")
    for r in rep.results:
        ev = "<br>".join(f"[{u.split('//')[-1][:48]}]({u})" for u in r.evidence_urls[:3]) or ("policy library" if r.requirement_id == "PROC-1.1" else "—")
        lvl = f" ({r.evidence_level})" if r.evidence_level else ""
        L.append(f"| {r.title} | {r.clause} | {VERDICT_MARK[r.verdict]} | {r.severity} | {r.reason.replace('|', '/')} | {ev}{lvl} | {r.evidence_as_of or '—'} |")
    L.append("")

    L.append("## 3. What we established about the vendor")
    L.append("")
    for f, fact in pf.facts.items():
        L.append(f"- **{f}** — {fact.display}  ")
        L.append(f"  confidence {fact.confidence:.2f} · {fact.evidence_level} · as of {fact.as_of or 'undated'} · sources: " + ", ".join(f"<{u}>" for u in fact.sources))
        for c in fact.conflicts:
            L.append(f"  - conflicting value seen: {c}")
    L.append("")

    if pf.quarantined or pf.rejected or pf.dropped:
        L.append("## 4. Security and validation notes")
        for u in pf.quarantined:
            L.append(f"- 🛑 Quarantined (prompt injection in page): <{u}>")
        for u in pf.rejected:
            L.append(f"- 🚫 Rejected (about a different company): <{u}>")
        for d in pf.dropped:
            L.append(f"- ⤵️ Dropped: {d}")
        for n in pf.notes:
            L.append(f"- ℹ️ {n}")
        L.append("")

    if rep.open_questions:
        L.append("## 5. Open questions for the vendor")
        L.append("")
        for i, q in enumerate(rep.open_questions, 1):
            L.append(f"{i}. **{q['id']}** (settles {q['clause']}): {q['question']}  ")
            L.append(f"   _Why:_ {q['why']}")
        L.append("")

    if rep.guardrail_notes:
        L.append("## 6. Guardrail notes")
        for n in rep.guardrail_notes:
            L.append(f"- {n}")
        L.append("")

    L.append("---")
    L.append("Generated by the Nimbu Mart vendor risk assistant (capstone project, Future with Shivank). Verdicts are computed by rules; a person decides.")
    return "\n".join(L)
